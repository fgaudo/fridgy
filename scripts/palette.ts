import {
  argbFromHex,
  DynamicScheme,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeVibrant,
  TonalPalette,
  Variant,
} from '@material/material-color-utilities'

// The app's key colors: the orange of the expiration badges, with the green and the red of the app's first palette,
// which the badges of freshness go through, from fresh to expired.
const source = '#fba551'
const tertiary = '#4fa34a'
const error = '#c43921'

// Material's vibrant variant, in the 2025 spec: everything but the tertiary and the error comes from the source, at
// a higher chroma than the default (tonal spot) keeps, for a saturated orange in the containers and warmer surfaces.
// The launcher icons and the splash screens are drawn on its surface.
const specVersion = '2025'

const scheme = (isDark: boolean) => {
  const sourceColorHct = Hct.fromInt(argbFromHex(source))
  const vibrant = new SchemeVibrant(sourceColorHct, isDark, 0, specVersion)
  return new DynamicScheme({
    sourceColorHct,
    variant: Variant.VIBRANT,
    contrastLevel: 0,
    isDark,
    specVersion,
    platform: 'phone',
    primaryPalette: vibrant.primaryPalette,
    secondaryPalette: vibrant.secondaryPalette,
    tertiaryPalette: TonalPalette.fromInt(argbFromHex(tertiary)),
    neutralPalette: vibrant.neutralPalette,
    neutralVariantPalette: vibrant.neutralVariantPalette,
    errorPalette: TonalPalette.fromInt(argbFromHex(error)),
  })
}

/** The surface role of a scheme, as a hex: what the launcher icons and the splash screens are drawn on. */
export const surface = (isDark: boolean) => hexFromArgb(scheme(isDark).getArgb(new MaterialDynamicColors().surface()))

const camelCase = (name: string) => name.replaceAll(/_([a-z])/g, (_, letter: string) => letter.toUpperCase())

/** Each role of a scheme, by its name in snake case, as ARGB. */
const roles = (isDark: boolean) => {
  const dynamicScheme = scheme(isDark)
  const colors = new MaterialDynamicColors()
  // `allColors` leaves these out.
  return [...colors.allColors, colors.surfaceVariant(), colors.surfaceTint(), colors.shadow(), colors.scrim()]
    // The key colors are not roles, and `primary_dim` and the like belong to the 2025 spec only.
    .filter((color) => !/_palette_key_color$|^(primary|secondary|tertiary|error)_dim$/.test(color.name))
    .map((color) => [color.name, dynamicScheme.getArgb(color)] as const)
}

/** An ARGB color with another alpha, out of 255. */
const withAlpha = (argb: number, alpha: number) => (((alpha & 0xff) << 24) | (argb & 0xffffff)) >>> 0

const hexArgb = (argb: number) => `#${argb.toString(16).padStart(8, '0')}`

/**
 * The roles of a scheme, with Material's disabled control: its content, on-surface at 38%, and its container,
 * on-surface at 12%.
 */
const schemeRoles = (isDark: boolean) => {
  const all = roles(isDark)
  const onSurface = all.find(([name]) => name === 'on_surface')?.[1] ?? 0
  return [
    ...all,
    ['disabled_content', withAlpha(onSurface, 0x61)],
    ['disabled_container', withAlpha(onSurface, 0x1f)],
  ] as const
}

/**
 * The Material 3 roles as Android's color resources, one file per scheme (`values`, `values-night`): Android picks the
 * scheme of the system's theme, and React Native's views name a role with `PlatformColor` (`src/styles.ts`).
 */
export const colorResources = (isDark: boolean) =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by \`bun run update-palette\` (scripts/palette.ts), from the app's key colors: do not edit. -->`,
    '<resources>',
    ...schemeRoles(isDark).map(([name, argb]) => `    <color name="md_${name}">${hexArgb(argb)}</color>`),
    '</resources>',
    '',
  ].join('\n')

/** The names of the roles, for `src/styles.ts`: the colors themselves are Android's resources. */
export const paletteModule = () =>
  [
    `// Generated by \`bun run update-palette\` (scripts/palette.ts), from the app's key colors: do not edit.`,
    `// The roles of Material 3, by the name of their color resource (\`md_<role>\`), which holds each scheme's value.`,
    'export const roles = {',
    ...schemeRoles(false).map(([name]) => `  ${camelCase(name)}: 'md_${name}',`),
    '} as const',
    '',
  ].join('\n')
