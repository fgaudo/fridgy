import {
  argbFromHex,
  DynamicScheme,
  Hct,
  hexFromArgb,
  MaterialDynamicColors,
  SchemeTonalSpot,
  TonalPalette,
  Variant,
} from '@material/material-color-utilities'

// The app's key colors: the orange of the expiration badges, and the green and the red of the app's first palette.
const source = '#fba551'
const tertiary = '#4fa34a'
const error = '#c43921'

// Material's default variant, tonal spot, in the 2025 spec: everything but the tertiary and the error comes from
// the source, a soft orange for the containers and warm surfaces. The launcher icons and the splash screens are
// drawn on its surface.
const specVersion = '2025'

const scheme = (isDark: boolean) => {
  const sourceColorHct = Hct.fromInt(argbFromHex(source))
  const tonalSpot = new SchemeTonalSpot(sourceColorHct, isDark, 0, specVersion)
  return new DynamicScheme({
    sourceColorHct,
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    specVersion,
    platform: 'phone',
    primaryPalette: tonalSpot.primaryPalette,
    secondaryPalette: tonalSpot.secondaryPalette,
    tertiaryPalette: TonalPalette.fromInt(argbFromHex(tertiary)),
    neutralPalette: tonalSpot.neutralPalette,
    neutralVariantPalette: tonalSpot.neutralVariantPalette,
    errorPalette: TonalPalette.fromInt(argbFromHex(error)),
  })
}

const linear = (channel: number) => {
  const c = channel / 255
  return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
}

const oklch = (argb: number) => {
  const [r, g, b] = [(argb >> 16) & 255, (argb >> 8) & 255, argb & 255].map(linear) as [number, number, number]
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const lightness = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s
  const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s
  const chroma = Math.hypot(a, bb)
  // A grey has no hue: `none` keeps color-mix from bending it towards one.
  const hue = chroma < 0.0005 ? 'none' : (((Math.atan2(bb, a) * 180) / Math.PI + 360) % 360).toFixed(2)
  return `oklch(${(lightness * 100).toFixed(2)}% ${chroma.toFixed(4)} ${hue})`
}

/** The Material 3 color roles of the light scheme, as Tailwind colors (`bg-primary-container`). */
export const palette = () => {
  const light = scheme(false)
  const colors = new MaterialDynamicColors()
  // `allColors` leaves these out.
  const roles = [...colors.allColors, colors.surfaceVariant(), colors.surfaceTint(), colors.shadow(), colors.scrim()]
    // The key colors are not roles, and `primary_dim` and the like belong to the 2025 spec only.
    .filter((color) => !/_palette_key_color$|^(primary|secondary|tertiary|error)_dim$/.test(color.name))
    .map((color) => {
      const argb = light.getArgb(color)
      const tone = Math.round(light.getHct(color).tone)
      return `  /* ${hexFromArgb(argb)}, tone ${tone} */\n  --color-${color.name.replaceAll('_', '-')}: ${oklch(argb)};`
    })
  return [
    `/* Generated by \`bun run update-palette\` (scripts/palette.ts), from the app's key colors: do not edit. */`,
    '@theme {',
    '  --color-*: initial;',
    ...roles,
    '}',
    '',
  ].join('\n')
}
